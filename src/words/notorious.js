const SET = new Set(NOTORIOUS);

/** Is this one of the words people actually get wrong? */
export function isNotorious(word) {
  return SET.has(String(word || '').toLowerCase());
}

/** The notorious words inside one tier's pool, in that pool's own order —
 *  so a substitution walks them with the same no-repeat discipline the tier
 *  walk uses on the pool it came from. */
export function notoriousIn(pool) {
  return pool.filter((w) => SET.has(w));
}

