/**
 * Word-bank builder (Phase 9) — merges the hand-authored WORD RUN list
 * with the Barsmith tiered banks (same catalog, different game) into one
 * generated module, re-tiered for READING AT SPEED.
 *
 * Barsmith tiers by syllabic weight because its verb is rhyme; WORD RUN
 * tiers by LENGTH because its verb is recognizing a spelling in a shrinking
 * time window — a longer word is more glance-hostile regardless of
 * syllables. Five tiers: 3-4 / 5 / 6-7 / 8-9 / 10-12 letters. Words longer
 * than 12 are dropped: at the deep-run reading windows they stop being a
 * fair glance-read on a phone plate.
 *
 * Run:  node tools/build-wordbank.mjs path/to/barsmith
 * Writes src/words/bank.js. Deterministic (sorted output) so the diff is
 * reviewable and the gate suites can pin counts.
 */

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

// Audience filter: Barsmith is a rap-writing tool and its register is
// adult in places. WORD RUN positions broad-audience-including-kids, so
// profanity, sexual content, hard drugs, self-harm and gore-adjacent
// vocabulary are excluded at build time (and gated in the suite).
export const EXCLUDED = [
  'arse', 'boob', 'piss', 'rape', 'nude', 'naked', 'bastard', 'hell',
  'damn', 'sexy', 'erotic', 'cocaine', 'heroin', 'liquor', 'tobacco',
  'suicide', 'homicide', 'murder', 'murderer', 'corpse', 'carcass',
  'pistol', 'rifle', 'bullet', 'ammo', 'gun', 'grenade', 'massacre',
  'slaughter', 'strangle', 'kill', 'killer', 'stab', 'wound', 'womb',
  'sperm', 'pussy', 'fanny', 'bosom', 'groin', 'sissy', 'slave', 'butch',
  'booty', 'loins', 'harlot', 'opium', 'whiskey', 'vodka', 'lynch',
];

// The gate suite imports EXCLUDED to verify the shipped bank; only an
// explicit CLI invocation performs the build (it needs a Barsmith clone).
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await build();
}

async function build() {
  const barsmithRoot = process.argv[2] || '../barsmith';
  const dataDir = path.join(barsmithRoot, 'src/data');
  const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
  const barsmith = [1, 2, 3].flatMap((t) => readJson(path.join(dataDir, `tier-${t}.json`)));

  // The existing hand-authored list stays in — it was curated for this game.
  const existing = (await import('../src/words/wordlist.js')).ALL_WORDS;

  const merged = [...new Set([...existing, ...barsmith])]
    .filter((w) => /^[a-z]+$/.test(w) && w.length >= 3 && w.length <= 12)
    .filter((w) => !EXCLUDED.includes(w))
    .sort();

  const tiers = [[], [], [], [], []];
  for (const w of merged) {
    const t = w.length <= 4 ? 0 : w.length === 5 ? 1 : w.length <= 7 ? 2 : w.length <= 9 ? 3 : 4;
    tiers[t].push(w);
  }

  const body = tiers.map((t, i) =>
    `// tier ${i}: ${t.length} words, length ${['3-4', '5', '6-7', '8-9', '10-12'][i]}\n` +
    `export const T${i} = ${JSON.stringify(t)};`).join('\n\n');

fs.writeFileSync('src/words/bank.js', `/**
 * GENERATED by tools/build-wordbank.mjs — do not hand-edit.
 * Sources: the original hand-authored WORD RUN list + the Barsmith
 * tiered banks (same catalog). ${merged.length} words, re-tiered by length
 * for reading-at-speed. Regenerate: node tools/build-wordbank.mjs <barsmith-root>
 */

${body}

export const BANK_TIERS = [T0, T1, T2, T3, T4];
`);

  console.log('bank.js written:', merged.length, 'words —', tiers.map((t) => t.length).join(' / '));
}
